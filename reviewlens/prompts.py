def _aspects_text(extraction) -> str:
    """Аспекти з екстракції у вигляді списку для промпта."""
    if not extraction.aspects:
        return "аспектів не знайдено"
    return "\n".join(f"- {a.aspect}, {a.sentiment}: «{a.quote}»" for a in extraction.aspects)


def build_writer_user(review: str, extraction) -> str:
    return f"Відгук:\n{review}\n\nАспекти з аналізу:\n{_aspects_text(extraction)}"


def build_critic_user(review: str, extraction, reply: str) -> str:
    return (
        f"Відгук:\n{review}\n\nАспекти з аналізу:\n{_aspects_text(extraction)}"
        f"\n\nЧернетка відповіді:\n{reply}"
    )


def build_rewrite_user(review: str, extraction, reply: str, issues: list[str]) -> str:
    notes = "\n".join(f"- {issue}" for issue in issues) or "- немає конкретних зауважень"
    return (
        f"Відгук:\n{review}\n\nАспекти з аналізу:\n{_aspects_text(extraction)}"
        f"\n\nПопередня чернетка:\n{reply}\n\nЗауваження перевіряючого:\n{notes}"
        "\n\nНапиши виправлену відповідь і поверни JSON."
    )


