EXTRACT_SYSTEM = """Ти аналізуєш відгук клієнта про заклад або товар. Знайди в ньому аспекти: конкретні теми, про які пише клієнт, з тональністю і цитатою-доказом.

Правила:
- aspect: одне з food, service, price, speed, atmosphere, quality, delivery, other.
  - food: їжа і напої (смак, температура, свіжість).
  - quality: чистота і стан заведення.
- sentiment: positive, negative або neutral (тональність саме цього аспекту).
- quote: ДОСЛІВНА копія фрагмента з відгуку, символ у символ, без перефразування і виправлень. Не менше 3 символів. Не вигадуй цитат.
- Якщо відгук містить кілька тем, поверни кожну окремо.
- Кожна пара «аспект + тональність» повертається один раз. Якщо одна тема повторюється в тексті, бери одну найпоказовішу цитату. Різні тональності одного аспекту (наприклад, food positive і food negative) повертай як окремі записи.
- Не вигадуй аспекти. Якщо в тексті немає конкретики (наприклад, «ну таке»), поверни "aspects": [].
- Аспект "other" використовуй лише для конкретної теми, яка не підпадає під решту категорій.
- urgency: low, medium або high, наскільки терміново потрібна реакція.
- language: код мови відгуку, наприклад "uk", "ru", "en".
- needs_human: true, якщо відгук потребує участі людини (погроза, юридичне питання, безпека, травма, отруєння), інакше false.

Поверни JSON такого вигляду:
{"aspects": [{"aspect": "food", "sentiment": "negative", "quote": "фрагмент з відгуку"}], "urgency": "low", "language": "uk", "needs_human": false}"""


def build_extract_user(review: str, error: str | None = None) -> str:
    """Текст для user-повідомлення. Якщо попередня спроба відхилена, додаємо причину."""
    if not error:
        return review
    return f"{review}\n\nПопередня відповідь відхилена: {error}. Виправ і поверни JSON ще раз."


